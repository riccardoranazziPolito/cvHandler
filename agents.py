from browser_use import Agent
from langchain_core.messages import HumanMessage, SystemMessage
from langchain_openai import ChatOpenAI
from weasyprint import HTML

from state import AgentState, JobAnalysisOutput

JOB_ANALYZER_SYSTEM_PROMPT = """You are the Job Analyzer Agent. You receive as input the text or URL of a Job Description and the user's base profile JSON.
Your task is to extract requirements and map them against the candidate's background.

Rule: Never fabricate or hallucinate skills or experiences that the user does not possess."""

CV_OPTIMIZER_SYSTEM_PROMPT = """You are the CV Optimizer Agent. You receive as input the user's base profile and the JSON generated by the Job Analyzer Agent.
Your task is to generate a tailored resume in clean, minimal HTML/CSS format ready to be compiled into a PDF via WeasyPrint.

Instructions:
1. Rewrite descriptions and bullet points for the user's projects/experiences to integrate the exact keywords (hard skills and technologies) required by the target company.
2. Prioritize and place at the top the experiences highlighted in the "match_points" of the analysis.
3. Maintain a highly technical, results-oriented, and quantified tone.
4. Output ONLY valid, self-contained HTML5 code (including an internal <style> block with clean, minimal styling suitable for an A4 PDF page). Do NOT wrap the response in markdown code blocks like ```html."""


def _simulate_job_text_extraction(job_url: str) -> str:
    """Simula l'estrazione del testo dell'offerta di lavoro a partire dall'URL."""
    return (
        f"Job Posting URL: {job_url}\n"
        "Position: AI & Data Engineer\n"
        "Company: TechCorp AI\n"
        "Requirements: Python, PySpark, LangGraph, Machine Learning, Docker, SQL. "
        "Strong problem-solving, teamwork, and communication skills."
    )


def _strip_markdown_fences(text: Any) -> str:
    """Rimuove eventuali blocchi markdown ```html ... ``` dall'output dell'LLM."""
    if not isinstance(text, str):
        text = str(text)
    cleaned = text.strip()
    if cleaned.startswith("```"):
        lines = cleaned.splitlines()
        if lines[0].startswith("```"):
            lines = lines[1:]
        if lines and lines[-1].strip() == "```":
            lines = lines[:-1]
        cleaned = "\n".join(lines).strip()
    return cleaned


def job_analyzer_node(state: AgentState) -> Dict[str, Any]:
    """
    Nodo LangGraph per l'Agente Analizzatore.
    Estrae i requisiti dall'offerta (simulando lo scraping se job_text non è presente)
    e restituisce l'output strutturato basato sul modello Pydantic JobAnalysisOutput.
    """
    job_url = state.get("job_url", "")
    job_text = state.get("job_text") or _simulate_job_text_extraction(job_url)
    user_profile = state.get("user_profile", {})

    llm = ChatOpenAI(model="gpt-4o", temperature=0)
    structured_llm = llm.with_structured_output(JobAnalysisOutput)

    user_prompt = (
        f"Job Description:\n{job_text}\n\n"
        f"Candidate Base Profile (JSON):\n{json.dumps(user_profile, indent=2, ensure_ascii=False)}"
    )

    analysis_output: JobAnalysisOutput = structured_llm.invoke([
        SystemMessage(content=JOB_ANALYZER_SYSTEM_PROMPT),
        HumanMessage(content=user_prompt),
    ])

    return {
        "job_text": job_text,
        "analysis_result": analysis_output.model_dump(),
    }


def cv_optimizer_node(state: AgentState) -> Dict[str, Any]:
    """
    Nodo LangGraph per l'Agente Ottimizzatore del CV.
    Genera il CV in HTML minimale tramite gpt-4o combinando user_profile e analysis_result,
    lo converte in PDF con WeasyPrint in /tmp/cv_ready.pdf e aggiorna cv_pdf_path.
    """
    user_profile = state.get("user_profile", {})
    analysis_result = state.get("analysis_result", {})

    llm = ChatOpenAI(model="gpt-4o", temperature=0.2)

    minimal_html_template = """<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <style>
        @page { size: A4; margin: 18mm; }
        body { font-family: Helvetica, Arial, sans-serif; font-size: 10.5pt; line-height: 1.4; color: #1a1a1a; margin: 0; }
        h1 { font-size: 20pt; margin: 0 0 4px 0; text-transform: uppercase; letter-spacing: 0.5px; }
        .contact { font-size: 9.5pt; color: #444; margin-bottom: 14px; }
        h2 { font-size: 11.5pt; text-transform: uppercase; border-bottom: 1px solid #222; padding-bottom: 2px; margin-top: 14px; margin-bottom: 8px; }
        .item { margin-bottom: 10px; }
        .item-header { display: flex; justify-content: space-between; font-weight: bold; }
        .item-sub { font-style: italic; font-size: 9.5pt; color: #555; margin-bottom: 3px; }
        ul { margin: 4px 0 0 18px; padding: 0; }
        li { margin-bottom: 3px; }
        .skills { font-size: 10pt; }
    </style>
</head>
<body>
    <!-- Populate candidate sections here: Header, Experience/Projects, Education, Skills -->
</body>
</html>"""

    user_prompt = (
        f"Candidate Base Profile (JSON):\n{json.dumps(user_profile, indent=2, ensure_ascii=False)}\n\n"
        f"Job Analysis Output (JSON):\n{json.dumps(analysis_result, indent=2, ensure_ascii=False)}\n\n"
        f"Base Minimal HTML Template to follow and populate:\n{minimal_html_template}"
    )

    response = llm.invoke([
        SystemMessage(content=CV_OPTIMIZER_SYSTEM_PROMPT),
        HumanMessage(content=user_prompt),
    ])

    html_content = _strip_markdown_fences(response.content)

    output_pdf_path = "/tmp/cv_ready.pdf"
    HTML(string=html_content).write_pdf(output_pdf_path)

    return {
        "cv_pdf_path": output_pdf_path,
    }


async def submitter_node(state: AgentState) -> Dict[str, Any]:
    """
    Nodo asincrono LangGraph per l'Agente Esecutore/Submitter tramite browser-use.
    Naviga all'URL dell'offerta, compila i campi anagrafici, carica il CV PDF e invia la candidatura.
    """
    job_url = state.get("job_url", "")
    user_profile = state.get("user_profile", {})
    personal_info = user_profile.get("personal_info", user_profile)
    cv_pdf_path = state.get("cv_pdf_path", "/tmp/cv_ready.pdf")

    personal_data_str = json.dumps(personal_info, ensure_ascii=False)

    task = (
        f"Vai a questo URL: {job_url}, "
        f"compila i campi anagrafici usando questi dati {personal_data_str}, "
        f"fai l'upload del file presente in {cv_pdf_path} e clicca su submit. "
        "Se un campo obbligatorio non è determinabile dai dati forniti, inserisci 'N/A' o '0'. "
        "Accetta le checkbox obbligatorie su privacy policy e termini di servizio. "
        "In caso di CAPTCHA, 2FA complessa o blocchi imprevisti, interrompi l'esecuzione e segnala la necessità di intervento manuale."
    )

    llm = ChatOpenAI(model="gpt-4o", temperature=0)

    try:
        agent = Agent(
            task=task,
            llm=llm,
        )
        history = await agent.run()

        final_result = history.final_result() if hasattr(history, "final_result") else str(history)
        if final_result and any(
            blocker in final_result.upper()
            for blocker in ["CAPTCHA", "2FA", "MANUAL", "INTERVENTION"]
        ):
            submission_status = f"REQUIRES_MANUAL_INTERVENTION: {final_result}"
        else:
            submission_status = f"SUCCESS: {final_result}" if final_result else "SUCCESS"
    except Exception as e:
        submission_status = f"FAILED: {str(e)}"

    return {
        "submission_status": submission_status,
    }

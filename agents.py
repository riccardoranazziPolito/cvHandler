def cv_optimizer_node(state: AgentState) -> Dict[str, Any]:
    """
    Nodo LangGraph per l'Agente Ottimizzatore del CV.
    Genera il CV in LaTeX (Jake's Resume style) tramite Gemini,
    lo compila con xelatex e salva /tmp/cv_ready.pdf.
    """
    import subprocess
    import tempfile
    import shutil

    user_profile = state.get("user_profile", {})
    analysis_result = state.get("analysis_result", {})

    llm = _make_llm(temperature=0.2).with_retry(**_RETRY_KWARGS)

    user_prompt = (
        f"Candidate Base Profile (JSON):\n{json.dumps(user_profile, indent=2, ensure_ascii=False)}\n\n"
        f"Job Analysis Output (JSON):\n{json.dumps(analysis_result, indent=2, ensure_ascii=False)}\n\n"
        f"Jake's Resume LaTeX Preamble (already defined, do NOT repeat it — populate only the document body):\n"
        f"{JAKES_RESUME_PREAMBLE}\n\n"
        "Now output the COMPLETE LaTeX document (including the preamble above verbatim, then the body). "
        "Use \\resumeSubheading for Experience and Education entries, \\resumeProjectHeading for Projects, "
        "\\resumeItem for bullet points. Include sections: Header (name + contact links), "
        "Education, Experience, Projects (if any), Technical Skills. "
        "Output ONLY raw LaTeX — no markdown fences."
    )

    response = llm.invoke([
        SystemMessage(content=CV_OPTIMIZER_SYSTEM_PROMPT),
        HumanMessage(content=user_prompt),
    ])

    latex_content = _strip_markdown_fences(response.content)

    # Write .tex to a temp directory and compile with xelatex
    tex_dir = tempfile.mkdtemp(prefix="cv_latex_")
    tex_path = os.path.join(tex_dir, "cv.tex")
    pdf_src = os.path.join(tex_dir, "cv.pdf")
    output_pdf_path = "/tmp/cv_ready.pdf"

    with open(tex_path, "w", encoding="utf-8") as f:
        f.write(latex_content)

    result = subprocess.run(
        ["xelatex", "-interaction=nonstopmode", "-output-directory", tex_dir, tex_path],
        capture_output=True,
        text=True,
        timeout=60,
    )

    if os.path.exists(pdf_src):
        shutil.copy(pdf_src, output_pdf_path)
    else:
        # Fallback: save LaTeX source for inspection
        shutil.copy(tex_path, "/tmp/cv_ready.tex")
        raise RuntimeError(
            f"xelatex compilation failed. LaTeX saved to /tmp/cv_ready.tex.\n"
            f"STDOUT: {result.stdout[-1000:]}\nSTDERR: {result.stderr[-500:]}"
        )

    return {
        "cv_pdf_path": output_pdf_path,
    }


def human_review_node(state: AgentState) -> Dict[str, Any]:
    """
    Nodo di revisione umana: apre il CV generato, mostra il riepilogo dell'analisi
    e chiede conferma da terminale prima di procedere con l'invio automatico.
    Restituisce submission_status = 'CANCELLED_BY_USER' se l'utente rifiuta.
    """
    import subprocess as _sp

    cv_pdf_path = state.get("cv_pdf_path", "/tmp/cv_ready.pdf")
    analysis_result = state.get("analysis_result", {})
    job_url = state.get("job_url", "")

    # --- Stampa riepilogo analisi ---
    print("\n" + "=" * 60)
    print("  📋  RIEPILOGO CANDIDATURA — REVISIONE RICHIESTA")
    print("=" * 60)
    print(f"  🏢  Azienda   : {analysis_result.get('company', 'N/A')}")
    print(f"  💼  Ruolo     : {analysis_result.get('job_title', 'N/A')}")
    print(f"  🔗  URL       : {job_url}")
    print(f"  📄  CV        : {cv_pdf_path}")

    hard_skills = analysis_result.get("required_hard_skills", [])
    match_points = analysis_result.get("match_points", [])

    if hard_skills:
        print(f"\n  🛠  Skill richieste : {', '.join(hard_skills)}")
    if match_points:
        print("\n  ✅  Match points:")
        for mp in match_points:
            print(f"      • {mp}")
    print("=" * 60)

    # --- Apri il PDF automaticamente ---
    if os.path.exists(cv_pdf_path):
        try:
            if sys.platform == "darwin":
                _sp.Popen(["open", cv_pdf_path])
            elif sys.platform.startswith("linux"):
                _sp.Popen(["xdg-open", cv_pdf_path])
            print(f"\n  📂  CV aperto in Anteprima: {cv_pdf_path}")
        except Exception:
            print(f"\n  ⚠️  Apri manualmente il CV: {cv_pdf_path}")
    else:
        print(f"\n  ⚠️  File CV non trovato: {cv_pdf_path}")

    # --- Chiedi conferma da terminale ---
    print("\n  Controlla il CV in Anteprima prima di confermare.\n")
    while True:
        answer = input("  Vuoi procedere con l'invio automatico della candidatura? [s/N]: ").strip().lower()
        if answer in ("s", "si", "sì", "y", "yes"):
            print("\n  ✅  Confermato — avvio invio candidatura...\n")
            return {}   # prosegui verso submitter_node
        elif answer in ("n", "no", "") :
            print("\n  ❌  Candidatura annullata dall'utente.\n")
            return {"submission_status": "CANCELLED_BY_USER"}
        else:
            print("  Risposta non valida. Digita 's' per confermare o 'n' per annullare.")


async def submitter_node(state: AgentState) -> Dict[str, Any]:
    """
    Nodo asincrono LangGraph per l'Agente Esecutore/Submitter tramite browser-use e Gemini.
    Naviga all'URL dell'offerta, compila i campi anagrafici, carica il CV PDF e invia la candidatura.
    """
    job_url = state.get("job_url", "")
    user_profile = state.get("user_profile", {})
    personal_info = user_profile.get("personal_info", user_profile)
    cv_pdf_path = state.get("cv_pdf_path", "/tmp/cv_ready.pdf")

    personal_data_str = json.dumps(personal_info, ensure_ascii=False)

    task = (
        f"Vai a questo URL: {job_url}, "
        f"compila i campi anagrafici usando questi dati {personal_data_str}, "
        f"fai l'upload del file presente in {cv_pdf_path} e clicca su submit. "
        "Se un campo obbligatorio non è determinabile dai dati forniti, inserisci 'N/A' o '0'. "
        "Accetta le checkbox obbligatorie su privacy policy e termini di servizio. "
        "In caso di CAPTCHA, 2FA complessa o blocchi imprevisti, interrompi l'esecuzione e segnala la necessità di intervento manuale."
    )

    # Use native Gemini support in browser-use
    llm = ChatGoogle(model="gemini-3.8-flash")

    try:
        agent = Agent(
            task=task,
            llm=llm,
        )
        history = await agent.run()

        final_result = history.final_result() if hasattr(history, "final_result") else str(history)
        if final_result and any(
            blocker in final_result.upper()
            for blocker in ["CAPTCHA", "2FA", "MANUAL", "INTERVENTION"]
        ):
            submission_status = f"REQUIRES_MANUAL_INTERVENTION: {final_result}"
        else:
            submission_status = f"SUCCESS: {final_result}" if final_result else "SUCCESS"
    except Exception as e:
        submission_status = f"FAILED: {str(e)}"

    return {
        "submission_status": submission_status,
    }
